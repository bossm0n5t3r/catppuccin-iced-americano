package icedamericano.tooling.ghostty

import java.io.IOException
import java.nio.file.Files
import java.nio.file.NoSuchFileException
import java.nio.file.Path
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

private val scalarTokens =
    listOf(
        "background" to "base",
        "foreground" to "text",
        "cursor-color" to "rosewater",
        "cursor-text" to "text",
        "selection-foreground" to "text",
        "split-divider-color" to "surface0",
    )
private val ansiTokens =
    listOf(
        "subtext1",
        "red",
        "green",
        "yellow",
        "blue",
        "pink",
        "teal",
        "surface2",
        "subtext0",
        "red",
        "green",
        "yellow",
        "blue",
        "pink",
        "teal",
        "surface1",
    )
private val hexPattern = Regex("#[0-9a-fA-F]{6}")
private val requiredTokens = (scalarTokens.map { it.second } + ansiTokens + "overlay2").distinct()

// Match upstream's mix(overlay2, base, 0.2): 20% overlay2, 80% base in sRGB,
// rounded to the nearest integer channel.
private fun selectionBackground(overlay2: String, base: String): String =
    buildString(7) {
        append('#')
        for (index in 1..5 step 2) {
            val overlay = overlay2[index].digitToInt(16) * 16 + overlay2[index + 1].digitToInt(16)
            val background = base[index].digitToInt(16) * 16 + base[index + 1].digitToInt(16)
            val mixed = (overlay + 4 * background + 2) / 5
            append("0123456789ABCDEF"[mixed ushr 4])
            append("0123456789ABCDEF"[mixed and 15])
        }
    }

internal fun renderGhosttyTheme(document: JsonElement): String {
    val palette =
        document as? JsonObject ?: throw IllegalArgumentException("palette must be an object")
    val colors =
        palette["colors"] as? JsonObject
            ?: throw IllegalArgumentException("palette.colors must be an object")
    val validated = requiredTokens.associateWith { token ->
        val field = "palette.colors.$token"
        val element = colors[token] ?: throw IllegalArgumentException("$field is required")
        val value = element as? JsonPrimitive
        require(value != null && value.isString) { "$field must be a #RRGGBB string" }
        require(hexPattern.matches(value.content)) { "$field must be #RRGGBB" }
        value.content.uppercase()
    }
    fun metadata(key: String): String {
        val value = palette[key] as? JsonPrimitive
        require(
            value != null &&
                value.isString &&
                value.content.isNotBlank() &&
                '\r' !in value.content &&
                '\n' !in value.content
        ) {
            "palette.$key must be a non-empty single-line string"
        }
        return value.content
    }
    val version = metadata("version")
    val status = metadata("status")
    return buildString {
        append("# Generated by ./gradlew :tooling:generateGhostty; do not edit.\n")
        append("# Production palette v$version; $status, not automatically adopted.\n")
        append("# Bright chromatic ANSI pairs reuse production tokens.\n")
        for ((key, token) in scalarTokens) append("$key = ${validated.getValue(token)}\n")
        val selection =
            selectionBackground(validated.getValue("overlay2"), validated.getValue("base"))
        append("selection-background = $selection\n")
        append('\n')
        for ((index, token) in ansiTokens.withIndex()) append(
            "palette = $index=${validated.getValue(token)}\n"
        )
    }
}

private fun expectedTheme(palettePath: Path, outputPath: Path): ByteArray {
    val document = Json.parseToJsonElement(Files.readString(palettePath))
    val expected = renderGhosttyTheme(document).toByteArray(Charsets.UTF_8)
    val sameNormalizedPath =
        palettePath.toAbsolutePath().normalize() == outputPath.toAbsolutePath().normalize()
    val sameExistingFile = Files.exists(outputPath) && Files.isSameFile(palettePath, outputPath)
    require(!sameNormalizedPath && !sameExistingFile) {
        "output must not overwrite input palette: $outputPath"
    }
    if (Files.isDirectory(outputPath)) throw IOException("output is a directory: $outputPath")
    return expected
}

fun generateGhostty(palettePath: Path, outputPath: Path) {
    val expected = expectedTheme(palettePath, outputPath)
    outputPath.toAbsolutePath().parent?.let { Files.createDirectories(it) }
    Files.write(outputPath, expected)
}

fun checkGhostty(palettePath: Path, outputPath: Path): GhosttyCheckResult {
    val expected = expectedTheme(palettePath, outputPath)
    val actual =
        try {
            Files.readAllBytes(outputPath)
        } catch (_: NoSuchFileException) {
            return GhosttyCheckResult.MISSING
        }
    return if (actual.contentEquals(expected)) GhosttyCheckResult.CURRENT
    else GhosttyCheckResult.STALE
}
