"""Generate the experimental Ghostty port from the production palette."""

import argparse
import json
import re
import sys
from pathlib import Path

SCALAR_TOKENS = (
    ("background", "base"),
    ("foreground", "text"),
    ("cursor-color", "blue"),
    ("cursor-text", "base"),
    ("selection-background", "surface1"),
    ("selection-foreground", "text"),
)
ANSI_TOKENS = (
    "text",
    "red",
    "green",
    "yellow",
    "blue",
    "pink",
    "teal",
    "subtext1",
    "subtext0",
    "red",
    "green",
    "yellow",
    "blue",
    "pink",
    "teal",
    "text",
)


def render_theme(palette: dict) -> str:
    """Render only validated production tokens, without modifying the input."""
    if not isinstance(palette, dict):
        raise ValueError("palette must be an object")  # noqa: TRY004 - palette validation API
    colors = palette.get("colors")
    if not isinstance(colors, dict):
        raise ValueError("palette.colors must be an object")  # noqa: TRY004 - validation API
    tokens = dict.fromkeys((*[token for _, token in SCALAR_TOKENS], *ANSI_TOKENS))
    for token in tokens:
        field = f"palette.colors.{token}"
        if token not in colors:
            raise ValueError(f"{field} is required")
        if not isinstance(colors[token], str):
            raise ValueError(f"{field} must be a #RRGGBB string")  # noqa: TRY004 - validation API
        if re.fullmatch(r"#[0-9a-fA-F]{6}", colors[token]) is None:
            raise ValueError(f"{field} must be #RRGGBB")
    for key in ("version", "status"):
        value = palette.get(key)
        if (
            not isinstance(value, str)
            or not value.strip()
            or "\r" in value
            or "\n" in value
        ):
            raise ValueError(f"palette.{key} must be a non-empty single-line string")
    lines = [
        "# Generated by python -m scripts.generate_ghostty; do not edit.",
        f"# Production palette v{palette['version']}; {palette['status']}, not automatically adopted.",
        "# Bright ANSI pairs reuse production tokens; no distinct bright colors.",
    ]
    lines.extend(f"{key} = {colors[token].upper()}" for key, token in SCALAR_TOKENS)
    lines.append("")
    lines.extend(
        f"palette = {index}={colors[token].upper()}"
        for index, token in enumerate(ANSI_TOKENS)
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--palette", type=Path, default=Path("palette/iced-americano.json")
    )
    parser.add_argument(
        "--output", type=Path, default=Path("ports/ghostty/iced-americano")
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        palette = json.loads(args.palette.read_text(encoding="utf-8"))
        expected = render_theme(palette).encode("utf-8")
        if args.output.resolve() == args.palette.resolve() or (
            args.output.exists() and args.output.samefile(args.palette)
        ):
            raise ValueError(f"output must not overwrite input palette: {args.output}")
        if args.check:
            try:
                actual = args.output.read_bytes()
            except FileNotFoundError:
                print(f"Missing generated theme: {args.output}", file=sys.stderr)
                return 1
            if actual != expected:
                print(f"Stale generated theme: {args.output}", file=sys.stderr)
                return 1
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
